"""The transaction type programs (COTRTLIC, COTRTUPC) on VSAM instead of Db2.

Upstream keeps the transaction types in the Db2 table CARDDEMO.TRANSACTION_TYPE. MVS 3.8J has no Db2: the table
is the TRANTYPE KSDS (the same records the batch programs read: type code, description), and each EXEC SQL
statement becomes a PERFORM of a paragraph made of KICKS file commands that sets SQLCODE as Db2 would
(0, +100 not found, -803 duplicate key, -532 the type still has categories, the ON DELETE RESTRICT of the
category table). A cursor reads the matching records into a table when it is opened; FETCH takes the next one.
The description filter (LIKE) is the helper CDLIKE, which ignores the case of letters: KICKS gives the program
the input in capitals, the descriptions are in mixed case.
"""
import re

TABLE = 200     # transaction types a cursor can hold (the type code is two digits)

WS = """
01 SQLCA.
  05 SQLCODE PIC S9(9) COMP VALUE 0.
  05 SQLERRM.
    10 SQLERRML PIC S9(4) COMP VALUE 0.
    10 SQLERRMC PIC X(70) VALUE SPACES.
01 CDSQL-VARS.
  05 CDSQL-RESP PIC S9(8) COMP VALUE 0.
  05 CDSQL-RESP-X PIC 9(4) VALUE 0.
  05 CDSQL-OK PIC X VALUE 'Y'.
  05 CDSQL-N PIC S9(4) COMP VALUE 0.
  05 CDSQL-I PIC S9(4) COMP VALUE 0.
  05 CDSQL-J PIC S9(4) COMP VALUE 0.
  05 CDSQL-KEY PIC X(2) VALUE SPACES.
  05 CDSQL-REC.
    10 CDSQL-REC-TYPE PIC X(2).
    10 CDSQL-REC-DESC PIC X(50).
    10 FILLER PIC X(8).
  05 CDSQL-CKEY.
    10 CDSQL-CKEY-TYPE PIC X(2).
    10 CDSQL-CKEY-CAT PIC X(4).
  05 CDSQL-CREC.
    10 CDSQL-CREC-TYPE PIC X(2).
    10 FILLER PIC X(58).
  05 CDSQL-ROWS OCCURS @TABLE1 TIMES.
    10 CDSQL-ROW-TYPE PIC X(2).
    10 CDSQL-ROW-DESC PIC X(50).
""".replace('@TABLE1', str(TABLE + 1))

DCLTRTYP = """
01 DCLTRANSACTION-TYPE.
  10 DCL-TR-TYPE PIC X(2).
  10 DCL-TR-DESCRIPTION.
    49 DCL-TR-DESCRIPTION-LEN PIC S9(4) USAGE COMP.
    49 DCL-TR-DESCRIPTION-TEXT PIC X(50).
"""
DCLTRCAT = """
01 DCLTRANSACTION-TYPE-CATEGORY.
  10 DCL-TRC-TYPE-CODE PIC X(2).
  10 DCL-TRC-TYPE-CATEGORY PIC X(4).
  10 DCL-TRC-CAT-DATA.
    49 DCL-TRC-CAT-DATA-LEN PIC S9(4) USAGE COMP.
    49 DCL-TRC-CAT-DATA-TEXT PIC X(50).
"""
# CSDB2RWY without the DSNTIAC message area (Db2's message formatter)
CSDB2RWY = """
05 WS-DB2-COMMON-VARS.
  10 WS-DISP-SQLCODE PIC ----9.
  10 WS-DUMMY-DB2-INT PIC S9(4) COMP-3 VALUE 0.
  10 WS-DB2-PROCESSING-FLAG PIC X(1).
    88 WS-DB2-OK VALUE '0'.
    88 WS-DB2-ERROR VALUE '1'.
  10 WS-DB2-CURRENT-ACTION PIC X(72) VALUE SPACES.
"""
# CSDB2RPY: the priming query has nothing to do; the message has the KICKS response instead of Db2's text
CSDB2RPY = """
9998-PRIMING-QUERY.
    MOVE 0 TO SQLCODE.
9998-PRIMING-QUERY-EXIT.
    EXIT.
9999-FORMAT-DB2-MESSAGE.
    MOVE SQLCODE TO WS-DISP-SQLCODE
    MOVE SPACES TO WS-LONG-MSG
    STRING FUNCTION TRIM(WS-DB2-CURRENT-ACTION) ' SQLCODE:' WS-DISP-SQLCODE ' ' SQLERRMC
        DELIMITED BY SIZE INTO WS-LONG-MSG
    END-STRING
    MOVE WS-LONG-MSG TO WS-RETURN-MSG.
9999-FORMAT-DB2-MESSAGE-EXIT.
    EXIT.
"""

PARAS = """
CDSQL-FAIL.
    MOVE -1 TO SQLCODE
    MOVE CDSQL-RESP TO CDSQL-RESP-X
    MOVE SPACES TO SQLERRMC
    STRING 'TRANTYPE FILE RESP ' CDSQL-RESP-X DELIMITED BY SIZE INTO SQLERRMC
    END-STRING.
CDSQL-SELECT.
    MOVE 0 TO SQLCODE
    MOVE DCL-TR-TYPE TO CDSQL-KEY
    EXEC CICS READ DATASET('TRANTYPE') INTO(CDSQL-REC) RIDFLD(CDSQL-KEY) RESP(CDSQL-RESP) END-EXEC
    EVALUATE TRUE
      WHEN CDSQL-RESP = DFHRESP(NORMAL)
        MOVE CDSQL-REC-TYPE TO DCL-TR-TYPE
        MOVE CDSQL-REC-DESC TO DCL-TR-DESCRIPTION-TEXT
        MOVE 50 TO DCL-TR-DESCRIPTION-LEN
      WHEN CDSQL-RESP = DFHRESP(NOTFND)
        MOVE 100 TO SQLCODE
      WHEN OTHER
        PERFORM CDSQL-FAIL
    END-EVALUATE.
CDSQL-UPDATE.
    MOVE 0 TO SQLCODE
    MOVE DCL-TR-TYPE TO CDSQL-KEY
    EXEC CICS READ DATASET('TRANTYPE') INTO(CDSQL-REC) RIDFLD(CDSQL-KEY) UPDATE RESP(CDSQL-RESP) END-EXEC
    EVALUATE TRUE
      WHEN CDSQL-RESP = DFHRESP(NORMAL)
        PERFORM CDSQL-DESC
        EXEC CICS REWRITE DATASET('TRANTYPE') FROM(CDSQL-REC) RESP(CDSQL-RESP) END-EXEC
        IF CDSQL-RESP NOT = DFHRESP(NORMAL)
          PERFORM CDSQL-FAIL
        END-IF
      WHEN CDSQL-RESP = DFHRESP(NOTFND)
        MOVE 100 TO SQLCODE
      WHEN OTHER
        PERFORM CDSQL-FAIL
    END-EVALUATE.
CDSQL-DESC.
    MOVE SPACES TO CDSQL-REC-DESC
    IF DCL-TR-DESCRIPTION-LEN > 0 AND DCL-TR-DESCRIPTION-LEN < 51
      MOVE DCL-TR-DESCRIPTION-TEXT(1:DCL-TR-DESCRIPTION-LEN) TO CDSQL-REC-DESC
    END-IF.
CDSQL-INSERT.
    MOVE 0 TO SQLCODE
    MOVE SPACES TO CDSQL-REC
    MOVE DCL-TR-TYPE TO CDSQL-REC-TYPE CDSQL-KEY
    PERFORM CDSQL-DESC
    EXEC CICS WRITE DATASET('TRANTYPE') FROM(CDSQL-REC) RIDFLD(CDSQL-KEY) RESP(CDSQL-RESP) END-EXEC
    EVALUATE TRUE
      WHEN CDSQL-RESP = DFHRESP(NORMAL)
        CONTINUE
      WHEN CDSQL-RESP = DFHRESP(DUPREC)
        MOVE -803 TO SQLCODE
        MOVE 'THE TYPE CODE IS ALREADY IN TRANTYPE' TO SQLERRMC
      WHEN OTHER
        PERFORM CDSQL-FAIL
    END-EVALUATE.
CDSQL-DELETE.
    MOVE 0 TO SQLCODE
    MOVE DCL-TR-TYPE TO CDSQL-KEY CDSQL-CKEY-TYPE
    MOVE LOW-VALUES TO CDSQL-CKEY-CAT
    EXEC CICS STARTBR DATASET('TRANCATG') RIDFLD(CDSQL-CKEY) GTEQ RESP(CDSQL-RESP) END-EXEC
    IF CDSQL-RESP = DFHRESP(NORMAL)
      EXEC CICS READNEXT DATASET('TRANCATG') INTO(CDSQL-CREC) RIDFLD(CDSQL-CKEY) RESP(CDSQL-RESP) END-EXEC
      IF CDSQL-RESP = DFHRESP(NORMAL) AND CDSQL-CREC-TYPE = DCL-TR-TYPE
        MOVE -532 TO SQLCODE
        MOVE 'TRANCATG' TO SQLERRMC
      END-IF
      EXEC CICS ENDBR DATASET('TRANCATG') END-EXEC
    END-IF
    IF SQLCODE = 0
      EXEC CICS DELETE DATASET('TRANTYPE') RIDFLD(CDSQL-KEY) RESP(CDSQL-RESP) END-EXEC
      EVALUATE TRUE
        WHEN CDSQL-RESP = DFHRESP(NORMAL)
          CONTINUE
        WHEN CDSQL-RESP = DFHRESP(NOTFND)
          MOVE 100 TO SQLCODE
        WHEN OTHER
          PERFORM CDSQL-FAIL
      END-EVALUATE
    END-IF.
"""

# the list program's cursors and count: the records that pass its two filters
LIST_PARAS = """
CDSQL-LOAD.
    MOVE 0 TO SQLCODE CDSQL-N
    MOVE LOW-VALUES TO CDSQL-KEY
    EXEC CICS STARTBR DATASET('TRANTYPE') RIDFLD(CDSQL-KEY) GTEQ RESP(CDSQL-RESP) END-EXEC
    IF CDSQL-RESP = DFHRESP(NORMAL)
      PERFORM CDSQL-LOAD-NEXT UNTIL CDSQL-RESP NOT = DFHRESP(NORMAL)
      EXEC CICS ENDBR DATASET('TRANTYPE') END-EXEC
    END-IF
    IF CDSQL-RESP NOT = DFHRESP(ENDFILE) AND CDSQL-RESP NOT = DFHRESP(NOTFND)
      PERFORM CDSQL-FAIL
    END-IF.
CDSQL-LOAD-NEXT.
    EXEC CICS READNEXT DATASET('TRANTYPE') INTO(CDSQL-REC) RIDFLD(CDSQL-KEY) RESP(CDSQL-RESP) END-EXEC
    IF CDSQL-RESP = DFHRESP(NORMAL)
      MOVE 'Y' TO CDSQL-OK
      IF WS-EDIT-TYPE-FLAG = '1' AND CDSQL-REC-TYPE NOT = WS-TYPE-CD-FILTER
        MOVE 'N' TO CDSQL-OK
      END-IF
      IF CDSQL-OK = 'Y' AND WS-EDIT-DESC-FLAG = '1'
        CALL 'CDLIKE' USING CDSQL-REC-DESC WS-TYPE-DESC-FILTER CDSQL-OK
      END-IF
      IF CDSQL-OK = 'Y' AND CDSQL-N < @TABLE
        ADD 1 TO CDSQL-N
        MOVE CDSQL-REC-TYPE TO CDSQL-ROW-TYPE(CDSQL-N)
        MOVE CDSQL-REC-DESC TO CDSQL-ROW-DESC(CDSQL-N)
      END-IF
    END-IF.
CDSQL-OPEN-FORWARD.
    PERFORM CDSQL-LOAD
    MOVE 1 TO CDSQL-I
    PERFORM CDSQL-UP UNTIL CDSQL-I > CDSQL-N OR CDSQL-ROW-TYPE(CDSQL-I) NOT < WS-START-KEY.
CDSQL-UP.
    ADD 1 TO CDSQL-I.
CDSQL-OPEN-BACKWARD.
    PERFORM CDSQL-LOAD
    MOVE 0 TO CDSQL-I
    MOVE 1 TO CDSQL-J
    PERFORM CDSQL-UP2 UNTIL CDSQL-I NOT < CDSQL-N OR CDSQL-ROW-TYPE(CDSQL-J) NOT < WS-START-KEY.
CDSQL-UP2.
    ADD 1 TO CDSQL-I CDSQL-J.
CDSQL-FETCH-FORWARD.
    IF CDSQL-I > CDSQL-N
      MOVE 100 TO SQLCODE
    ELSE
      MOVE 0 TO SQLCODE
      MOVE CDSQL-ROW-TYPE(CDSQL-I) TO DCL-TR-TYPE
      MOVE CDSQL-ROW-DESC(CDSQL-I) TO DCL-TR-DESCRIPTION-TEXT
      MOVE 50 TO DCL-TR-DESCRIPTION-LEN
      ADD 1 TO CDSQL-I
    END-IF.
CDSQL-FETCH-BACKWARD.
    IF CDSQL-I < 1
      MOVE 100 TO SQLCODE
    ELSE
      MOVE 0 TO SQLCODE
      MOVE CDSQL-ROW-TYPE(CDSQL-I) TO DCL-TR-TYPE
      MOVE CDSQL-ROW-DESC(CDSQL-I) TO DCL-TR-DESCRIPTION-TEXT
      MOVE 50 TO DCL-TR-DESCRIPTION-LEN
      SUBTRACT 1 FROM CDSQL-I
    END-IF.
CDSQL-COUNT.
    PERFORM CDSQL-LOAD
    MOVE CDSQL-N TO WS-RECORDS-COUNT.
""".replace('@TABLE', str(TABLE))

# EXEC SQL statement (blanks normalized, prefix) -> its replacement
STMTS = [
    ('INCLUDE SQLCA', WS),
    ('INCLUDE DCLTRTYP', DCLTRTYP),
    ('INCLUDE DCLTRCAT', DCLTRCAT),
    ('INCLUDE CSDB2RWY', CSDB2RWY),
    ('DECLARE ', ''),
    ('OPEN C-TR-TYPE-FORWARD', 'PERFORM CDSQL-OPEN-FORWARD'),
    ('OPEN C-TR-TYPE-BACKWARD', 'PERFORM CDSQL-OPEN-BACKWARD'),
    ('FETCH C-TR-TYPE-FORWARD INTO :DCL-TR-TYPE ,:DCL-TR-DESCRIPTION', 'PERFORM CDSQL-FETCH-FORWARD'),
    ('FETCH C-TR-TYPE-BACKWARD INTO :DCL-TR-TYPE ,:DCL-TR-DESCRIPTION', 'PERFORM CDSQL-FETCH-BACKWARD'),
    ('CLOSE C-TR-TYPE-', 'MOVE 0 TO SQLCODE'),
    ('SELECT COUNT(1) INTO :WS-RECORDS-COUNT FROM CARDDEMO.TRANSACTION_TYPE', 'PERFORM CDSQL-COUNT'),
    ('SELECT TR_TYPE ,TR_DESCRIPTION INTO :DCL-TR-TYPE ,:DCL-TR-DESCRIPTION FROM CARDDEMO.TRANSACTION_TYPE '
     'WHERE TR_TYPE = :DCL-TR-TYPE', 'PERFORM CDSQL-SELECT'),
    ('UPDATE CARDDEMO.TRANSACTION_TYPE SET TR_DESCRIPTION = :DCL-TR-DESCRIPTION WHERE TR_TYPE = :DCL-TR-TYPE',
     'PERFORM CDSQL-UPDATE'),
    ('INSERT INTO CARDDEMO.TRANSACTION_TYPE (TR_TYPE, TR_DESCRIPTION) VALUES ( :DCL-TR-TYPE ,:DCL-TR-DESCRIPTION)',
     'PERFORM CDSQL-INSERT'),
    ('DELETE FROM CARDDEMO.TRANSACTION_TYPE WHERE TR_TYPE = :DCL-TR-TYPE', 'PERFORM CDSQL-DELETE'),
    ('INCLUDE CSDB2RPY', CSDB2RPY + PARAS + LIST_PARAS),
]


def to_vsam(text):
    """every EXEC SQL statement of COTRTLIC or COTRTUPC -> its KICKS replacement; COTRTUPC, which has no
    CSDB2RPY, gets the paragraphs at its end. Db2's message text (SQLERRM, a varying-length string) is SQLERRMC."""
    seen = set()
    def one(m):
        s = ' '.join(m.group(1).split())
        for k, (pre, new) in enumerate(STMTS):
            if s.startswith(pre):
                seen.add(k); return new
        raise ValueError('EXEC SQL not handled: ' + s[:80])
    text = re.sub(r'EXEC\s+SQL\s+(.*?)\s*END-EXEC', one, text, flags=re.S)
    if len(STMTS) - 1 not in seen:
        text = text.rstrip() + '\n' + PARAS
    return re.sub(r'SQLERRM\s+OF\s+SQLCA', 'SQLERRMC', text)
